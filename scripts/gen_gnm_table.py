"""Generates the libGnm table the GNM hooks bind: src/title/generated/pes_gnm_table.inc.

Each row is a function of the title's libGnm region (LO-HI, guest addresses) that the engine
calls, or a command buffer method: its offset, the prologue bytes moved into the hook stub (whole
instructions, at least 5 bytes, none RIP-relative or a branch), its static call sites, whether it
calls the command buffer's reserve callback, and a name. The name is the one from --names when
given, else a generic name from the address; the PM4 signature from gnm_sigs.py follows it.

Usage: gen_gnm_table.py --region LO-HI [--names names.txt] [-o out.inc] region.asm gnm_cg.txt gnm_sigs.txt
  region.asm: objdump -D -b binary -m i386:x86-64 -M intel --insn-width=16 --adjust-vma=LO on the
              region's bytes (the region extracted from the title's eboot)
  gnm_cg.txt: scripts/gnm/callgraph.py output for LO-HI
  gnm_sigs.txt: scripts/gnm/gnm_sigs.py output for region.asm and gnm_cg.txt
--region is required: the region is the title's gnm_region (measured, not assumed). --names is
optional; its lines are "offset name" ('#' starts a comment).
"""
import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_OUT = os.path.join(ROOT, 'src', 'title', 'generated', 'pes_gnm_table.inc')
INS = re.compile(r'^\s*([0-9a-f]+):\t((?:[0-9a-f]{2} )+)\s*\t(.*)$')
CB_CALL = re.compile(r'call\s+QWORD PTR \[r\w+\+0x18\]')
PROLOGUE_MIN = 5
PROLOGUE_MAX = 15


def region(text):
    lo_s, sep, hi_s = text.partition('-')
    if not sep:
        raise argparse.ArgumentTypeError('expected LO-HI in hex, e.g. 0x1068000-0x10a0000')
    try:
        lo, hi = int(lo_s, 16), int(hi_s, 16)
    except ValueError:
        raise argparse.ArgumentTypeError('LO and HI must be hex addresses')
    if not 0 <= lo < hi:
        raise argparse.ArgumentTypeError('need 0 <= LO < HI')
    return lo, hi


def load_code(path):
    code = {}
    with open(path, encoding='utf-8', errors='replace') as f:
        for line in f:
            m = INS.match(line)
            if m:
                code[int(m.group(1), 16)] = (bytes.fromhex(m.group(2).replace(' ', '')), m.group(3).strip())
    return code


def load_sigs(path):
    sigs = {}
    with open(path, encoding='utf-8', errors='replace') as f:
        for line in f:
            head, _, sig = line.partition(': ')
            if head.strip():
                sigs[int(head.split()[0], 16)] = sig.strip()
    return sigs


def load_names(path):
    names = {}
    if path is None:
        return names
    with open(path, encoding='utf-8', errors='replace') as f:
        for line in f:
            parts = line.split('#', 1)[0].split()
            if len(parts) >= 2:
                names[int(parts[0], 16)] = parts[1]
    return names


def prologue(code, fn, size):
    """The relocatable prologue at fn (at least PROLOGUE_MIN bytes), or None."""
    pro, a = b'', fn
    while len(pro) < PROLOGUE_MIN:
        if a not in code:
            return None
        b, text = code[a]
        mnem = text.split()[0] if text else '(bad)'
        if ('rip' in text or mnem.startswith('j')
                or mnem in ('call', 'ret', 'loop', 'int3', '(bad)') or a >= fn + size):
            return None
        pro += b
        a += len(b)
    return pro if len(pro) <= PROLOGUE_MAX else None


def build_rows(code, cg_path, sigs, lo, hi, names):
    rows, skipped = [], 0
    with open(cg_path, encoding='utf-8', errors='replace') as f:
        for line in f:
            p = line.split()
            if len(p) < 7:
                continue
            fn, size, sites, ext = int(p[0], 16), int(p[2]), int(p[4]), int(p[6])
            if not lo <= fn < hi or size < 16:
                continue
            # Command buffer methods are hooked even when only libGnm itself calls them (a caller in
            # Gnmx may not be hooked); other functions only when the engine calls them.
            cb = any(CB_CALL.search(code[x][1]) for x in range(fn, fn + size) if x in code)
            if ext == 0 and not cb:
                continue
            pro = prologue(code, fn, size)
            if pro is None:
                skipped += 1
                continue
            sig = sigs.get(fn, '')
            name = names.get(fn, f'gnm_{fn:07x}') + (': ' + sig if sig else '')
            name = name.replace('"', "'").replace('\\', '/')[:120]
            rows.append((fn, pro, sites, name, cb))
    return rows, skipped


def render(rows, skipped, lo, hi):
    out = [
        '// SPDX-License-Identifier: GPL-2.0-or-later',
        f'// Generated by scripts/gen_gnm_table.py from the title eboot, region 0x{lo:x}-0x{hi:x}: the libGnm',
        '// functions the engine calls (offset, prologue bytes moved into the hook stub, static call sites,',
        '// command buffer method: calls the reserve callback, name).',
        f'// {len(rows)} functions; {skipped} skipped (prologue not relocatable).',
    ]
    for fn, pro, sites, name, cb in rows:
        bs = ', '.join(f'0x{x:02x}' for x in pro)
        out.append(f'{{0x{fn:x}, {len(pro)}, {{{bs}}}, {sites}, {int(cb)}, "{name}"}},')
    return '\n'.join(out) + '\n'


def main(argv=None):
    ap = argparse.ArgumentParser(description='Generate the libGnm hook table.')
    ap.add_argument('--region', type=region, required=True, metavar='LO-HI')
    ap.add_argument('--names', metavar='FILE', help='optional "offset name" lines')
    ap.add_argument('-o', '--output', default=DEFAULT_OUT, metavar='FILE')
    ap.add_argument('region_asm')
    ap.add_argument('callgraph')
    ap.add_argument('sigs')
    args = ap.parse_args(argv)
    lo, hi = args.region
    code = load_code(args.region_asm)
    rows, skipped = build_rows(code, args.callgraph, load_sigs(args.sigs), lo, hi,
                               load_names(args.names))
    if not rows:
        print('gen_gnm_table: no relocatable functions in the region; no table written '
              '(an empty table cannot compile: delete the generated file to build without it)',
              file=sys.stderr)
        return 1
    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, 'w', encoding='utf-8', newline='\n') as f:
        f.write(render(rows, skipped, lo, hi))
    print(f'gen_gnm_table: {len(rows)} functions, {skipped} skipped -> {args.output}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
